# To add two numbers we used to use the imperative approach i.e take two variables and just add them using arithmetic operation
a = 10
b = 12
print(a+b)

# The problem arises when you need to add two more variables in that case you have to create two more variables
c = 5
d = 6
print(a+b+c+d)

# To solve this we had other approach i.e Functional approach 
def sum(n1,n2):
    return n1+n2

print(sum(5,6))
print(sum(8,9))

# This approach was very good as you don't have to write the code multiple times. Once you write the code you can use it multuple times

